"""Generate src/data.rs from the official COEFF01W.txt ... COEFF12W.txt files.

Usage: python3 tools/import_data.py DIRECTORY
Download the inputs from ITU-R-Study-Group-3/ITU-R-HF at the pinned commit below,
under P533/Data, including 'P1239-3 Decile Factors.txt'. This is a maintainer
tool only; building and calling the Rust library require neither Python nor I/O.
"""

import hashlib
import math
from pathlib import Path
import re
import sys

COMMIT = "82017594a1c6cacfaa7e86954c4ae7b3a5825a3d"
SOURCE = f"https://github.com/ITU-R-Study-Group-3/ITU-R-HF/tree/{COMMIT}/P533/Data"
FIELDS = {
    "xf2": ("FOF2", (2, 76, 13)),
    "xfm3": ("M3000", (2, 49, 9)),
    "fakp": ("FAKP", (6, 16, 29)),
    "fakabp": ("FAKABP", (6, 2)),
    "dud": ("DUD", (5, 12, 5)),
    "fam": ("FAM", (12, 14)),
}


def array(values, shape, depth=0):
    if len(shape) == 1:
        return "[" + ", ".join(next(values) for _ in range(shape[0])) + "]"
    indent = "    " * (depth + 1)
    return "[\n" + "".join(
        indent + array(values, shape[1:], depth + 1) + ",\n"
        for _ in range(shape[0])
    ) + "    " * depth + "]"


def generate(directory):
    data = {name: [] for name in FIELDS}
    hashes = []
    for month in range(1, 13):
        path = directory / f"COEFF{month:02}W.txt"
        raw = path.read_bytes()
        hashes.append(f"// {path.name}: {hashlib.sha256(raw).hexdigest()}")
        text = raw.decode()
        assert re.match(rf"month =\s*{month}\s", text)
        headers = list(re.finditer(r"^([a-z][a-z0-9]*)\(([^)]+)\)\s*$", text, re.M))
        fields = {}
        for i, header in enumerate(headers):
            if header[1] not in FIELDS and header[1] not in ("if2", "ifm3"):
                continue
            end = headers[i + 1].start() if i + 1 < len(headers) else len(text)
            shape = tuple(reversed([int(n) for n in header[2].split(",")]))
            values = text[header.end():end].lower().split()
            assert len(values) == math.prod(shape), header[1]
            assert all(math.isfinite(float(v)) for v in values), header[1]
            fields[header[1]] = shape, values
        assert list(map(int, fields["if2"][1])) == [11, 35, 53, 63, 67, 69, 71, 73, 75, 6]
        assert list(map(int, fields["ifm3"][1])) == [6, 22, 34, 40, 44, 46, 48, 48, 48, 4]
        for name, (_, shape) in FIELDS.items():
            assert fields[name][0] == shape
            data[name].extend(fields[name][1])

    path = directory / "P1239-3 Decile Factors.txt"
    raw = path.read_bytes()
    hashes.append(f"// {path.name}: {hashlib.sha256(raw).hexdigest()}")
    rows = [line.split() for line in raw.decode(errors="replace").splitlines()
            if re.match(r"^\s*\d{1,2}[°�]", line)]
    assert len(rows) == 2 * 3 * 3 * 19
    deciles = []
    for start in range(0, len(rows), 19):
        block = rows[start:start + 19]
        assert [int(row[0][:-1]) for row in block] == list(range(90, -1, -5))
        for row in reversed(block):
            assert len(row) == 25
            assert all(0 < float(v) < 2 for v in row[1:])
            deciles.extend(row[1:])

    out = ["// Generated by tools/import_data.py; do not edit by hand.",
           f"// Source: {SOURCE}", "// Input SHA-256 hashes:", *hashes,
           "// Decile values also checked against the supplied P.1239-4 Tables 2 and 3.",
           "pub(crate) const F2_K: [usize; 9] = [11, 35, 53, 63, 67, 69, 71, 73, 75];",
           "pub(crate) const M3_K: [usize; 7] = [6, 22, 34, 40, 44, 46, 48];"]
    arrays = [(name, (12, *shape), data[key]) for key, (name, shape) in FIELDS.items()]
    arrays.append(("DECILES", (2, 3, 3, 19, 24), deciles))
    for name, shape, values in arrays:
        assert len(values) == math.prod(shape)
        kind = "f64"
        for size in reversed(shape):
            kind = f"[{kind}; {size}]"
        out.append(f"\n#[rustfmt::skip]\npub(crate) static {name}: {kind} = {array(iter(values), shape)};")
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    output = Path(__file__).resolve().parents[1] / "src/data.rs"
    output.write_text(generate(Path(sys.argv[1])))
