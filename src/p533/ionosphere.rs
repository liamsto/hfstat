    #[test]
    fn solar_activity_follows_p533() {
        let mut pt = ControlPt {
            l: Location::new(30.25, -60.75).unwrap().radians(),
            ..ControlPt::default()
        };
        magfit::<300>(&mut pt);
        let low = Maps::new(Month::Jan, 12, 0).at(&basis(&pt));
        let high = Maps::new(Month::Jan, 12, 100).at(&basis(&pt));
        let middle = Maps::new(Month::Jan, 12, 50).at(&basis(&pt));
        assert!((middle.0 - (low.0 + high.0) / 2.0).abs() < 1e-10);
        assert!((middle.1 - (low.1 + high.1) / 2.0).abs() < 1e-10);
        let capped = Maps::new(Month::Jan, 12, 160).at(&basis(&pt));
        let above = Maps::new(Month::Jan, 12, 200).at(&basis(&pt));
        assert_eq!(above.0, capped.0);
        assert!((above.1 - (2.0 * high.1 - low.1)).abs() < 1e-10);
        assert!((above.1 - capped.1).abs() > 0.01);
    }
