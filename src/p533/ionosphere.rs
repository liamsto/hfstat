use std::f64::consts::PI;

/// Hourly coefficients shared by all control points in a prediction.
/// Interpolation and harmonic summation retain the order of P.1239-4 evaluation.
pub(super) struct Maps {
    fof2: [f64; 76],
    m3000: [f64; 49],
}

impl Maps {
    pub(super) fn new(month: Month, hour: usize, ssn: u16) -> Self {
        let t = (hour as f64 - 12.0) * PI / 12.0;
        let mut time = [1.0; 13];
        for j in 1..=6 {
            (time[2 * j - 1], time[2 * j]) = (j as f64 * t).sin_cos();
        }
        // P.533-14 §3.4 caps foF2 only, unlike P.1239-4 §3.1 which caps both.
        Self {
            fof2: coefficients(&FOF2[month.index()], &time, f64::from(ssn.min(160))),
            m3000: coefficients(&M3000[month.index()], &time, f64::from(ssn)),
        }
    }

    pub(super) fn at(&self, basis: &([f64; 76], [f64; 49])) -> (f64, f64) {
        (
            basis
                .0
                .iter()
                .zip(&self.fof2)
                .fold(0.0, |sum, (g, c)| sum + g * c),
            basis
                .1
                .iter()
                .zip(&self.m3000)
                .fold(0.0, |sum, (g, c)| sum + g * c),
        )
    }
}

fn coefficients<const N: usize, const H: usize>(
    coeff: &[[[f64; H]; N]; 2],
    time: &[f64; 13],
    ssn: f64,
) -> [f64; N] {
    let r = ssn / 100.0;
    core::array::from_fn(|i| {
        let mut value = 0.0;
        for (j, t) in time[..H].iter().enumerate() {
            value += t * ((1.0 - r) * coeff[0][i][j] + r * coeff[1][i][j]);
        }
        value
    })
}

/// Geographic basis, independent of month, hour and sunspot number. The point's
/// dip must already use the 1960 magnetic field at 300 km.
pub(super) fn basis(pt: &ControlPt) -> ([f64; 76], [f64; 49]) {
    let cos_lat = pt.l.lat.cos().max(0.0);
    let sin_x = pt.dip.1.atan2(cos_lat.sqrt()).sin();
    let harmonics: [_; 8] = core::array::from_fn(|m| ((m + 1) as f64 * pt.l.lng).sin_cos());
    (
        geography(&F2_K, cos_lat, sin_x, &harmonics),
        geography(&M3_K, cos_lat, sin_x, &harmonics),
    )
}

fn geography<const N: usize>(
    k: &[usize],
    cos_lat: f64,
    sin_x: f64,
    harmonics: &[(f64, f64); 8],
) -> [f64; N] {
    let mut g = [0.0; N];
    let mut power = 1.0;
    for value in &mut g[..=k[0]] {
        *value = power;
        power *= sin_x;
    }
    let mut cos_power = cos_lat;
    for (m, bounds) in k.windows(2).enumerate() {
        let (sin, cos) = harmonics[m];
        power = cos_power;
        for i in (bounds[0] + 1..=bounds[1]).step_by(2) {
            g[i] = power * cos;
            g[i + 1] = power * sin;
            power *= sin_x;
        }
        cos_power *= cos_lat;
    }

    g
}

